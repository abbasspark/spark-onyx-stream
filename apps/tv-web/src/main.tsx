import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './app';
import { detectPlatform, registerKeys } from './lib/platform';
import './styles.css';

registerKeys(detectPlatform(navigator.userAgent));

const root = document.getElementById('root');
if (root) {
  createRoot(root).render(
    <StrictMode>
      <App />
    </StrictMode>,
  );
}
